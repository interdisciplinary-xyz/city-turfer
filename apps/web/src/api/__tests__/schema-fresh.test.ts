import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
import { expect, it } from 'vitest';

const SPEC = new URL('../../../../api/openapi.json', import.meta.url);
const GENERATED = fileURLToPath(new URL('../schema.gen.ts', import.meta.url));

/** The committed types match apps/api/openapi.json; else run `pnpm --filter @cityturfer/web run api:types`. */
it('schema.gen.ts is generated from the current apps/api/openapi.json', async () => {
  const header =
    '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
  const fresh = header + astToString(await openapiTS(SPEC));
  const formatted = await format(fresh, { ...(await resolveConfig(GENERATED)), filepath: GENERATED });
  expect(formatted === (await readFile(GENERATED, 'utf8')), 'run: pnpm --filter @cityturfer/web run api:types').toBe(
    true
  );
}, 30_000);
