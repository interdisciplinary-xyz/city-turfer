"""Draw the CityTurfer wordmark as outlined SVG paths in Anton (brand-system skill, Logo).

Outlines render the same everywhere (no font needed by Chrome, Figma or the store tools). Set in
capitals like every display line (docs/decisions/brand-typography-2026-10-22.md, amendments
2026-10-27): both words are Anton (a static font with one weight, 400), used for the wordmark only;
headlines stay Big Shoulders Display. The whole word CITYTURFER is one solid colour (founder decision
2026-10-27: no Ramp gradient on "TURFER"; the colour lives in the app icon / mark). Two files:
`wordmark.svg` for dark backgrounds (white), `wordmark-light.svg` for light ones (night).

Usage (fonttools + uharfbuzz in a virtualenv); the font is kept in packages/brand/fonts/ (OFL-Anton.txt),
from https://github.com/google/fonts/raw/main/ofl/anton/Anton-Regular.ttf:
  python outline-wordmark.py packages/brand/fonts/Anton-Regular.ttf packages/brand/svg
"""
import os
import sys

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

SIZE = 180  # font size in SVG units
TRACKING = 0.03  # letter-spacing as a share of the font size (Anton is set tight: 0.03 keeps Y and T apart at 20 px)
PAD = 12
NIGHT, WHITE = '#0B0D12', '#FFFFFF'
VARIANTS = {
    'wordmark.svg': {'fill': WHITE, 'note': 'dark backgrounds'},
    'wordmark-light.svg': {'fill': NIGHT, 'note': 'light backgrounds'},
}


def shape(blob, text, x0):
    """Shape `text` with HarfBuzz; return (svg path, advance end x, bounds)."""
    face = hb.Face(blob)
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {'kern': True, 'liga': True})
    tt = TTFont(FONT_PATH)
    glyphs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    scale = SIZE / tt['head'].unitsPerEm
    pen = SVGPathPen(None, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
    bounds = BoundsPen(None)
    x = x0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        # flip y (font units are y-up, SVG is y-down); baseline at y = SIZE
        matrix = (scale, 0, 0, -scale, x + pos.x_offset * scale, SIZE - pos.y_offset * scale)
        glyphs[name].draw(TransformPen(pen, matrix))
        glyphs[name].draw(TransformPen(bounds, matrix))
        x += pos.x_advance * scale + TRACKING * SIZE
    return pen.getCommands(), x - TRACKING * SIZE, bounds.bounds


def main(out_dir):
    blob = hb.Blob.from_file_path(FONT_PATH)
    city, city_end, cb = shape(blob, 'CITY', 0)
    turfer, end, tb = shape(blob, 'TURFER', city_end + TRACKING * SIZE)
    x_min, y_min = min(cb[0], tb[0]), min(cb[1], tb[1])
    x_max, y_max = max(cb[2], tb[2]), max(cb[3], tb[3])
    vx, vy = x_min - PAD, y_min - PAD
    w, h = x_max - x_min + 2 * PAD, y_max - y_min + 2 * PAD
    for file, v in VARIANTS.items():
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vx:.1f} {vy:.1f} {w:.1f} {h:.1f}" width="{w:.0f}" height="{h:.0f}" role="img" aria-label="CityTurfer">
  <!-- CityTurfer wordmark for {v['note']}. Anton outlines, generated by packages/brand/scripts/outline-wordmark.py: do not edit by hand. -->
  <path fill="{v['fill']}" d="{city}{turfer}"/>
</svg>
'''
        with open(os.path.join(out_dir, file), 'w') as f:
            f.write(svg)
        print(file, f'{w:.0f}x{h:.0f}')


if __name__ == '__main__':
    FONT_PATH = sys.argv[1]
    main(sys.argv[2])
