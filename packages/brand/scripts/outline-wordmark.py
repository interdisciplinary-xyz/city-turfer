"""Draw the CityTurfer wordmark as outlined SVG paths in Archivo (brand-system skill, Logo).

Outlines render the same everywhere (no font needed by Chrome, Figma or the store tools). "City" is
Archivo Expanded Medium, "Turfer" Archivo Expanded Black filled with the Ramp, running from
bottom-left to top-right. Two files: `wordmark.svg` for dark backgrounds, `wordmark-light.svg` for
light ones ("City" in night; "Turfer" uses only faint -> glow, which stay legible on white).

Usage (fonttools + uharfbuzz in a virtualenv):
  python outline-wordmark.py Archivo-VF.ttf packages/brand/svg
"""
import os
import sys

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

SIZE = 180  # font size in SVG units
TRACKING = -0.02  # letter-spacing as a share of the font size (display: -2% to -4%)
PAD = 12
NIGHT, BLAZING, FAINT, GLOW, STRONG = '#0B0D12', '#FFF3C4', '#7B2FF7', '#F72FA8', '#FFB02E'
VARIANTS = {
    'wordmark.svg': {'city': BLAZING, 'ramp': [(0, GLOW), (0.7, STRONG), (1, BLAZING)], 'note': 'dark backgrounds'},
    'wordmark-light.svg': {'city': NIGHT, 'ramp': [(0, FAINT), (1, GLOW)], 'note': 'light backgrounds'},
}


def shape(blob, text, wght, x0):
    """Shape `text` with HarfBuzz at the given weight; return (svg path, advance end x)."""
    face = hb.Face(blob)
    font = hb.Font(face)
    font.set_variations({'wdth': 125, 'wght': wght})
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {'kern': True, 'liga': True})
    tt = TTFont(FONT_PATH)
    glyphs = tt.getGlyphSet(location={'wdth': 125, 'wght': wght})
    order = tt.getGlyphOrder()
    scale = SIZE / tt['head'].unitsPerEm
    pen = SVGPathPen(None, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
    bounds = BoundsPen(None)
    x = x0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        # flip y (font units are y-up, SVG is y-down); baseline at y = SIZE
        matrix = (scale, 0, 0, -scale, x + pos.x_offset * scale, SIZE - pos.y_offset * scale)
        glyphs[name].draw(TransformPen(pen, matrix))
        glyphs[name].draw(TransformPen(bounds, matrix))
        x += pos.x_advance * scale + TRACKING * SIZE
    return pen.getCommands(), x - TRACKING * SIZE, bounds.bounds


def main(out_dir):
    blob = hb.Blob.from_file_path(FONT_PATH)
    city, city_end, cb = shape(blob, 'City', 500, 0)
    turfer, end, tb = shape(blob, 'Turfer', 900, city_end + 0.01 * SIZE)
    x_min, y_min = min(cb[0], tb[0]), min(cb[1], tb[1])
    x_max, y_max = max(cb[2], tb[2]), max(cb[3], tb[3])
    vx, vy = x_min - PAD, y_min - PAD
    w, h = x_max - x_min + 2 * PAD, y_max - y_min + 2 * PAD
    for file, v in VARIANTS.items():
        stops = '\n'.join(f'      <stop offset="{o}" stop-color="{c}"/>' for o, c in v['ramp'])
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vx:.1f} {vy:.1f} {w:.1f} {h:.1f}" width="{w:.0f}" height="{h:.0f}" role="img" aria-label="CityTurfer">
  <!-- CityTurfer wordmark for {v['note']}. Archivo Expanded outlines, generated by packages/brand/scripts/outline-wordmark.py: do not edit by hand. -->
  <defs>
    <linearGradient id="ramp" gradientUnits="userSpaceOnUse" x1="{tb[0]:.1f}" y1="{tb[3]:.1f}" x2="{tb[2]:.1f}" y2="{tb[1]:.1f}">
{stops}
    </linearGradient>
  </defs>
  <path fill="{v['city']}" d="{city}"/>
  <path fill="url(#ramp)" d="{turfer}"/>
</svg>
'''
        with open(os.path.join(out_dir, file), 'w') as f:
            f.write(svg)
        print(file, f'{w:.0f}x{h:.0f}')


if __name__ == '__main__':
    FONT_PATH = sys.argv[1]
    main(sys.argv[2])
