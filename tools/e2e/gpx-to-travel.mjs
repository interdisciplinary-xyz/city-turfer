#!/usr/bin/env node
// Convert a GPX fixture into a Maestro `travel` subflow, so a flow can move the
// simulated device itself (simctl replays are reset when a Maestro flow ends).
//
//   node tools/e2e/gpx-to-travel.mjs tools/fixtures/run-5k-outliers-pause.gpx --metres 900 --speed 3.5 > e2e/subflows/travel-run.yaml

import { readFileSync } from 'node:fs';
import { haversine, parseGpx } from '../lib/geo.mjs';

const argv = process.argv.slice(2);
const file = argv[0];
const opt = (n, d) => (argv.includes(`--${n}`) ? Number(argv[argv.indexOf(`--${n}`) + 1]) : d);
const metres = opt('metres', 800);
const speed = opt('speed', 3.5); // m/s
const step = opt('step', 40); // metres between travel points

const { points } = parseGpx(readFileSync(file, 'utf8'));
const out = [points[0]];
let along = 0,
  sinceLast = 0;
for (let i = 1; i < points.length && along < metres; i++) {
  const d = haversine(points[i - 1], points[i]);
  along += d;
  sinceLast += d;
  if (sinceLast >= step) {
    out.push(points[i]);
    sinceLast = 0;
  }
}
console.log(`# Generated by tools/e2e/gpx-to-travel.mjs from ${file} (${Math.round(along)} m at ${speed} m/s)`);
console.log('appId: com.turftrack.poc');
console.log('---');
console.log('- travel:');
console.log('    points:');
for (const p of out) console.log(`      - "${p.lat.toFixed(6)}, ${p.lon.toFixed(6)}"`);
console.log(`    speed: ${speed}`);
