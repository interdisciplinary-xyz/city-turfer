const NEUTRAL_HEX = new Set(['#FFFFFF', '#000000']);

/** Brand hex values newly hard-coded in an app source file (they must come from @cityturfer/brand). */
export function brandHexFindings(relPath, before, after, brandHexes) {
  if (!/^apps\/(mobile|web)\/src\//.test(relPath) || IS_TEST.test(relPath)) {
    return [];
  }
  const hexes = (text) => new Set((text.match(/#[0-9a-fA-F]{6}\b/g) ?? []).map((h) => h.toUpperCase()));
  const old = hexes(before);
  const added = [...hexes(after)].filter((h) => !old.has(h) && brandHexes.has(h) && !NEUTRAL_HEX.has(h));
  return added.length
    ? [
        {
          rule: 'brand-hex',
          message: `hard-coded brand colour ${added.join(', ')}; import it from @cityturfer/brand (mobile: apps/mobile/src/constants/colors.ts re-exports it). See the brand-system skill.`,
        },
      ]
    : [];
}

