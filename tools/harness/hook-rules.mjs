/** Files Claude must never write, whatever the content. */
export function protectedFileFindings(relPath) {
  const out = [];
  if (relPath === 'CHANGELOG.md') {
    out.push({
      rule: 'changelog',
      message:
        'CHANGELOG.md is generated by commit-and-tag-version in release.yml on main. Never edit it by hand; write a Conventional Commit instead (docs/process/release-manager.md).',
    });
  }
  const secret = classify(relPath);
  if (secret?.level === 'block') {
    out.push({
      rule: 'secret-file',
      message: `${relPath} is a ${secret.what}. It must never be created in the repo (tools/check-secret-files.mjs would block the commit anyway). Keep synthetic GPX in apps/mobile/tools/fixtures/ and real data on the device.`,
    });
  }
  if (relPath.startsWith('apps/mobile/ios/') || relPath.startsWith('apps/mobile/android/')) {
    out.push({
      rule: 'generated-native',
      message:
        'apps/mobile/ios and apps/mobile/android are generated by `expo prebuild` (Continuous Native Generation) and git-ignored. Change app.json, a config plugin in apps/mobile/plugins/ or a native module in apps/mobile/modules/ instead.',
    });
  }
  return out;
}

