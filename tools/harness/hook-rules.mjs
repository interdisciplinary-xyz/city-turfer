/**
 * Pure rules behind the Claude Code hooks in .claude/hooks/. They turn CLAUDE.md's hard rules and
 * docs/process/release-manager.md into feedback at the moment Claude edits a file or runs a command,
 * instead of minutes later in pre-push or CI. No I/O here: the hook scripts read stdin, the file
 * system and git, then call these functions. Tested in tools/__tests__/hook-rules.test.mjs.
 *
 * Each rule returns findings `{ rule, message }`. The hook decides what a finding does:
 *   deny  — the tool call does not run (Claude sees the message and must change course)
 *   ask   — the user confirms in the permission prompt
 *   warn  — the call runs; the message is fed back to Claude
 *
 * Limits: imports and shell commands are matched with regexes, not parsed. The real gates stay
 * dependency-cruiser, ESLint, the git hooks and CI; these rules only move the feedback earlier.
 */
import { posix } from 'node:path';

import { classify } from '../check-secret-files.mjs';

// ---------------------------------------------------------------------------
// Edits: reconstruct the file as it will be after the tool call
// ---------------------------------------------------------------------------

/**
 * @param {string} tool  Edit | Write | MultiEdit
 * @param {Record<string, any>} input  the tool_input of the hook payload
 * @param {string} before  current file content ('' when the file does not exist)
 */
export function contentAfter(tool, input, before) {
  if (tool === 'Write') {
    return input.content ?? '';
  }
  const edits = tool === 'MultiEdit' ? (input.edits ?? []) : [input];
  let text = before;
  for (const e of edits) {
    if (typeof e.old_string !== 'string' || typeof e.new_string !== 'string' || !text.includes(e.old_string)) {
      continue;
    }
    text = e.replace_all ? text.split(e.old_string).join(e.new_string) : text.replace(e.old_string, () => e.new_string);
  }
  return text;
}

