const MOBILE_SRC = 'apps/mobile/src/';
const IS_TEST = /(^|\/)(__tests__|test-support)\/|\.test\.tsx?$/;

const FRAMEWORKS_DOMAIN =
  /^(react|react-native|react-native-nitro-modules|@kingstinct\/react-native-healthkit|@[^/]+\/react-native-[^/]+|@react-native[^/]*\/[^/]+|expo[^/]*|zustand|h3-js|@maplibre\/[^/]+|better-sqlite3|@cityturfer\/ui)(\/|$)/;
const FRAMEWORKS_APPLICATION = /^(react|react-native|expo[^/]*|h3-js|@maplibre\/[^/]+|@cityturfer\/ui)(\/|$)/;

/** Import specifiers in a TS/JS source (static, re-export, side-effect, dynamic, require). */
export function importSpecifiers(source) {
  const specs = new Set();
  const re =
    /(?:^|[\s;])(?:import|export)\s+(?:type\s+)?[^'"`;]*?\sfrom\s*['"]([^'"]+)['"]|(?:^|[\s;])import\s*['"]([^'"]+)['"]|\bimport\(\s*['"]([^'"]+)['"]\s*\)|\brequire\(\s*['"]([^'"]+)['"]\s*\)/g;
  let m;
  while ((m = re.exec(source))) {
    specs.add(m[1] ?? m[2] ?? m[3] ?? m[4]);
  }
  return [...specs];
}

/**
 * Where an import lands: `{ pkg }` for a package, `{ src }` for a path under apps/mobile/src (relative
 * to it, e.g. 'contexts/territory/domain/claim'), or `{}` for anything else.
 */
export function resolveImport(fromRelPath, spec) {
  if (spec.startsWith('@/')) {
    return { src: posix.normalize(spec.slice(2)) };
  }
  if (spec.startsWith('.')) {
    const target = posix.normalize(posix.join(posix.dirname(fromRelPath), spec));
    return target.startsWith(MOBILE_SRC) ? { src: target.slice(MOBILE_SRC.length) } : {};
  }
  return { pkg: spec };
}

/** Layer of a file under apps/mobile/src, or null outside it / in tests. */
export function layerOf(relPath) {
  if (!relPath.startsWith(MOBILE_SRC) || IS_TEST.test(relPath)) {
    return null;
  }
  const p = relPath.slice(MOBILE_SRC.length);
  if (p.startsWith('shared-kernel/')) {
    return { layer: 'domain', context: 'shared-kernel' };
  }
  const ctx = p.match(/^contexts\/([^/]+)\/(domain|application|infrastructure|ui)\//);
  if (ctx) {
    return { layer: ctx[2], context: ctx[1] };
  }
  const ctxRoot = p.match(/^contexts\/([^/]+)\//);
  if (ctxRoot) {
    return { layer: 'context-root', context: ctxRoot[1] };
  }
  if (p.startsWith('app/')) {
    return { layer: 'screen', context: null };
  }
  if (p.startsWith('constants/')) {
    return { layer: 'constants', context: null };
  }
  return { layer: 'other', context: null };
}

const OUTER = /^(platform|composition-root|wiring|app|ui-kit)(\/|$)/;
const CTX_LAYER = /^contexts\/([^/]+)\/(domain|application|infrastructure|ui)\//;

/** Dependency-rule violations of one import, or null. */
function violation(from, target) {
  const { layer, context } = from;
  if (target.pkg) {
    if (layer === 'domain' && FRAMEWORKS_DOMAIN.test(target.pkg)) {
      return `domain/shared-kernel imports the framework/library \`${target.pkg}\``;
    }
    if (layer === 'application' && FRAMEWORKS_APPLICATION.test(target.pkg)) {
      return `application layer imports the framework/library \`${target.pkg}\``;
    }
    return null;
  }
  if (!target.src) {
    return null;
  }
  const into = target.src.match(CTX_LAYER);
  if (layer === 'domain' && (OUTER.test(target.src) || (into && into[2] !== 'domain'))) {
    return `domain/shared-kernel reaches outward into \`src/${target.src}\``;
  }
  if (
    layer === 'application' &&
    (/^(composition-root|wiring|app|ui-kit)(\/|$)/.test(target.src) || (into && /infrastructure|ui/.test(into[2])))
  ) {
    return `application layer imports infrastructure/UI \`src/${target.src}\``;
  }
  if (context && context !== 'shared-kernel' && into && into[1] !== context) {
    return `context \`${context}\` reaches into \`${into[1]}\`'s ${into[2]}/ layer; use its index.ts / contract.ts`;
  }
  if (layer === 'screen' && (/^platform(\/|$)/.test(target.src) || (into && into[2] !== 'ui'))) {
    return `screen imports \`src/${target.src}\`; screens use a context's ui/ hooks and public API only`;
  }
  if (layer === 'constants' && !target.src.startsWith('constants/')) {
    return `src/constants/ is a leaf and imports nothing from the app (\`src/${target.src}\`)`;
  }
  return null;
}

/**
 * Dependency-rule findings introduced by an edit (imports present after but not before), so legacy
 * code never blocks an unrelated change. dependency-cruiser in `pnpm test` stays the real gate.
 */
export function dependencyFindings(relPath, before, after) {
  const from = layerOf(relPath);
  if (!from || !/\.(ts|tsx|js|mjs)$/.test(relPath)) {
    return [];
  }
  const old = new Set(importSpecifiers(before));
  const out = [];
  for (const spec of importSpecifiers(after)) {
    if (old.has(spec)) {
      continue;
    }
    const why = violation(from, resolveImport(relPath, spec));
    if (why) {
      out.push({
        rule: 'dependency-rule',
        message: `${why} (import '${spec}'). See the ddd-architecture skill and apps/mobile/.dependency-cruiser.cjs.`,
      });
    }
  }
  return out;
}

